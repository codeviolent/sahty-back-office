import 'package:flutter/widgets.dart';

import 'app_text_key.dart';

enum AppLocale {
  fr(Locale('fr'), TextDirection.ltr),
  ar(Locale('ar'), TextDirection.rtl);

  const AppLocale(this.locale, this.direction);

  final Locale locale;
  final TextDirection direction;
}

class AppLocalizationScope extends InheritedWidget {
  const AppLocalizationScope({
    super.key,
    required this.locale,
    required this.onLocaleChanged,
    required super.child,
  });

  final AppLocale locale;
  final ValueChanged<AppLocale> onLocaleChanged;

  static AppLocalizationScope of(BuildContext context) {
    final scope = context
        .dependOnInheritedWidgetOfExactType<AppLocalizationScope>();
    assert(scope != null, 'AppLocalizationScope is missing from the tree.');
    return scope!;
  }

  @override
  bool updateShouldNotify(AppLocalizationScope oldWidget) {
    return locale != oldWidget.locale;
  }
}

extension AppLocalizationsX on BuildContext {
  AppLocale get appLocale => AppLocalizationScope.of(this).locale;

  /// Safe translation: falls back to French, then the key name if both are missing.
  String tr(AppTextKey key) =>
      _localizedValues[appLocale]?[key] ??
      _localizedValues[AppLocale.fr]?[key] ??
      '[${key.name}]';

  TextDirection get appDirection => appLocale.direction;

  void setAppLocale(AppLocale locale) {
    AppLocalizationScope.of(this).onLocaleChanged(locale);
  }
}

